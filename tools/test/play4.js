// usage: node play3.js <html> <outprefix> · plays Màn 3 through and screenshots each room
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const THREE = fs.readFileSync(path.join(__dirname,'../../prototype/chung/three.min.js'));
(async()=>{
  const [,, file, out, upto] = process.argv;
  const b = await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const p = await b.newPage({viewport:{width:1280,height:720}});
  if(process.env.JRCHECK) await require('./jrcheck').attach(p);
  const errs=[]; p.on('pageerror', e=>errs.push(e.message)); p.on('console', m=>{ if(m.type()==='error' && !/ERR_FAILED/.test(m.text())) errs.push(m.text()); });
  await p.route('**/three.min.js', r=>r.fulfill({body:THREE, contentType:'application/javascript'}));
  await p.route('https://fonts.googleapis.com/**', r=>r.abort());
  await p.goto('file://'+path.resolve(file));
  await p.waitForTimeout(2500); if(errs.length){ console.log('LOAD ERRORS\n'+errs.join('\n')); }
  const stage = await p.$('#stage');
  const snap = async n=>{ if(process.env.NOSHOT) return; await p.evaluate(()=>{ __game.pause=false; }); await p.waitForTimeout(350); await p.evaluate(()=>{ __game.pause=true; }); await stage.screenshot({path:`${out}-${n}.png`}); };
  await p.evaluate(()=>{
    const g = window.__game; window.G = g;
    g.pause = true;
    window.idle = n=>{ g.keys.left = g.keys.right = false; g.tick(n||1); };
    window.waitFree = ()=>{ let n=0; while(g.busy && n++<4000) g.tick(1); g.tick(10); };
    window.walkTo = (x, max)=>{ let n=0; while(Math.abs(g.P.x - x) > .12 && n++ < (max||2000)){ g.keys.right = g.P.x < x; g.keys.left = g.P.x > x; g.tick(1); } g.keys.left = g.keys.right = false; g.tick(4); let m=0; while(!g.P.ground && m++<120) g.tick(1); return g.P.x; };
    window.peel = (s, dir)=>{ g.grab(); g.tick(2); let n=0; while(g.P.grab && n++ < 3000){ g.keys[dir||'right'] = true; g.tick(1); } g.keys.left = g.keys.right = false; g.tick(2); };
    window.jump = (dir, hold)=>{ g.jump(); if(dir) g.keys[dir] = true; g.tick(hold||50); g.keys.left = g.keys.right = false; g.tick(20); };
    window.st = (l)=>({l, x:+g.P.x.toFixed(2), y:+g.P.y.toFixed(2), obj:g.objective, flies:g.flies, relic:g.relic});
    window.use = ()=>{ G.grab(); G.tick(3); };
    window.fold = f=>{ let n=0; while(G.held.form !== f && n++<6){ G.fold(); } G.tick(2); };
    window.SH = id=>G.sheets.find(s=>s.id===id);
  });
  const log = async s=>{ try { console.log(JSON.stringify(await p.evaluate(s))); } catch(e){ console.log('EVAL ERR', e.message.slice(0,300)); } };
  await p.evaluate(()=>{ window.wet = ()=>+G.rain.wet.toFixed(2); });
  await p.evaluate(()=>{ G.introTick(60*6); }); await snap('0-intro');
  await p.evaluate(()=>{ G.skipIntro(); idle(30); });
  await snap('1a');
  // room 1: without the awning the street is too long
  await log(()=>{ walkTo(16.5); idle(5); return st('r1 run without awning wet='+wet()+' x='+G.P.x); });
  await log(()=>{ idle(60); walkTo(5.4); peel(SH('B')); waitFree(); return st('r1 awning wet='+wet()); });
  await log(()=>{ idle(90); return st('r1 under awning wet='+wet()); });
  await snap('1b');
  await log(()=>{ walkTo(14.6); return st('r1 ff1 wet='+wet()); });
  await log(()=>{ walkTo(20.0); idle(60); return st('r2 under tin wet='+wet()); });
  await snap('2a');
  await log(()=>{ walkTo(20.6); peel(SH('N')); waitFree(); return st('r2 non learned='+G.learned+' held='+G.held.on); });
  await log(()=>{ fold('non'); walkTo(27.3); jump('right',30); walkTo(29.8); jump('right',26); walkTo(32.6); jump('right',30); walkTo(33.8); jump(null,30); walkTo(35.0); walkTo(36.9); jump('right',30); walkTo(42.6); return st('r2 crossed wear='+G.held.wear.toFixed(2)+' wet='+wet()+' held='+G.held.on); });
  await snap('2b');
  await log(()=>{ walkTo(45.4); idle(20); return st('r3 shelter'); });
  await log(()=>{ if(G.held.on){ G.keys.right=false; } walkTo(52.6); peel(SH('U')); waitFree(); idle(40); return st('r3 umbrella wet='+wet()); });
  await snap('3a');
  await log(()=>{ walkTo(45.9); peel(SH('P')); waitFree(); return st('r3 patch held='+G.held.on+' form='+G.held.form); });
  await log(()=>{ if(G.held.form){ fold(null); } walkTo(54.4); jump('right',22); walkTo(55.5); idle(10); use(); waitFree(); return st('r3 patched filled='+G.slots[0].filled+' wet='+wet()); });
  await snap('3b');
  await log(()=>{ walkTo(55.5); jump(null,12); G.keys.left=true; G.tick(8); G.keys.left=false; idle(30); return st('r3 on canopy?'); });
  await log(()=>{ G.jump(); let n=0; while(G.P.vy < 10 && n++<200) G.tick(1); const vy = G.P.vy; G.keys.right = true; n=0; while(!(G.P.ground && G.P.y > 6.5) && n++<200) G.tick(1); G.keys.right=false; walkTo(60.5); idle(30); return st('r4 on roof bounceVy='+vy.toFixed(1)+' wet='+wet()); });
  await snap('4a');
  await log(()=>{ walkTo(71.2); G.grab(); G.tick(2); let n=0; while(n++<40){ G.keys.left=true; G.tick(1);} G.keys.left=false; G.grab(); G.tick(2); const w0 = wet(); idle(90); return st('r4 V1 shelf p='+SH('V').p.toFixed(2)+' wetAtRelease='+w0+' wetAfter='+wet()); });
  await snap('4b');
  await log(()=>{ walkTo(78.6); G.grab(); G.tick(2); let n=0; while(n++<40){ G.keys.left=true; G.tick(1);} G.keys.left=false; G.grab(); G.tick(2); idle(60); return st('r4 V2 p='+SH('W').p.toFixed(2)+' wet='+wet()); });
  await log(()=>{ walkTo(79.6); jump('right',40); walkTo(89.4); idle(60); return st('r5 tin wet='+wet()); });
  await log(()=>{ peel(SH('T')); waitFree(); walkTo(95.3); const x=G.P.x; use(); waitFree(); return st('r5 leak0 at '+x.toFixed(2)+' filled='+G.slots.map(s=>s.filled)+' wet='+wet()); });
  await log(()=>{ walkTo(89.4); idle(150); peel(SH('T')); waitFree(); walkTo(100.3); use(); waitFree(); return st('r5 leak1 filled='+G.slots.map(s=>s.filled)+' wet='+wet()); });
  await snap('5a-tin');
  await log(()=>{ walkTo(107.0); peel(SH('F')); waitFree(); fold('maybay'); walkTo(108.3); G.keys.right=true; G.tick(1); G.keys.right=false; use(); let n=0; while(n++<200) G.tick(1); waitFree(); return st('r6 plane hit='+G.targets.map(t=>t.hit)); });
  await snap('6a-line');
  await log(()=>{ walkTo(113); walkTo(117.2); walkTo(119.2); walkTo(121.2); walkTo(123.2); idle(30); return st('r6 down wet='+wet()); });
  await log(()=>{ walkTo(123.0); peel(SH('K')); waitFree(); fold('thuyen'); walkTo(125.0); use(); idle(20); return st('r7 boat on='+G.boat.on); });
  await log(()=>{ idle(150); walkTo(123.0); peel(SH('K')); waitFree(); fold('non'); walkTo(127.0); walkTo(143.6); return st('r7 crossed wet='+wet()+' wear='+G.held.wear.toFixed(2)); });
  await snap('7a-canal');
  await log(()=>{ walkTo(144.2); peel(SH('H')); waitFree(); walkTo(144.2); peel(SH('H')); waitFree(); return st('r8 hien L='+SH('H').L); });
  await log(()=>{ let mx=0; const tick0=G.tick; walkTo(154.6); mx=Math.max(mx,wet()); jump('right',22); mx=Math.max(mx,wet()); walkTo(156.2); jump('right',22); mx=Math.max(mx,wet()); walkTo(157.8); jump('right',22); mx=Math.max(mx,wet()); walkTo(159.6); jump('right',30); mx=Math.max(mx,wet()); walkTo(163.6); idle(60); return st('r8 up maxWet~'+mx); });
  await snap('8a-hien');
  await log(()=>{ walkTo(163.4); peel(SH('C')); waitFree(); fold('non'); walkTo(167.6); peel(SH('S')); return st('r9 cloud done='+SH('S').done+' wear='+G.held.wear.toFixed(2)+' wet='+wet()); });
  await p.evaluate(()=>{ G.tick(60*5.5); }); await snap('5c-rainbow');
  await p.evaluate(()=>{ G.tick(60*4); }); await snap('5d-bay');
  await log(()=>{ let n=0; while(!G.winReady && n++<3000) G.tick(2); return st('won='+G.won+' winReady='+G.winReady+' rain='+G.rain.k.toFixed(2)); });
  await snap('5b');
  if(!process.env.NOSHOT){ await p.evaluate(()=>{ __game.pause=false; }); await p.waitForTimeout(800); await stage.screenshot({path:`${out}-6-win.png`}); }
  if(errs.length) console.log('ERRORS\n'+errs.join('\n'));
  await b.close();
})();
